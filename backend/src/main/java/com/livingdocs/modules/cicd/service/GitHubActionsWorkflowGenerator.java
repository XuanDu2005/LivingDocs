package com.livingdocs.modules.cicd.service;

/**
 * Generates a GitHub Actions workflow YAML file that runs LivingDocs
 * drift detection on every pull request and enforces the workspace's
 * merge gate.
 *
 * <p>The generated workflow:
 * <ul>
 *     <li>Triggers on {@code pull_request} (opened / synchronize / reopened).</li>
 *     <li>Checks out the changed repository.</li>
 *     <li>Asks LivingDocs whether the pull request may be merged, and
 *         fails the job when the answer is "no".</li>
 * </ul>
 *
 * <h2>Why the workflow asks instead of deciding</h2>
 *
 * <p>The workflow used to take a {@code blockOnCritical} flag and fail
 * the build on its own. That flag came from a query parameter on the
 * generator endpoint, not from the workspace — so the workspace's
 * {@code merge_policy_critical} setting was decorative: a workflow
 * generated while the policy was {@code WARN} kept failing builds, and
 * one generated after it was switched to {@code BLOCK} kept passing
 * them.
 *
 * <p>The generated workflow therefore never decides anything. It calls
 * LivingDocs, which reads the workspace's own policy, evaluates the
 * merge gate, and answers. The workflow's only job is to honour the
 * answer.
 *
 * <p>This service does <b>not</b> commit the file itself — it returns the
 * rendered YAML which can be committed manually, or pushed automatically
 * by a privileged admin token in a future iteration.
 */
public final class GitHubActionsWorkflowGenerator {

    private GitHubActionsWorkflowGenerator() {}

    /**
     * Render the workflow.
     *
     * @param backendUrl  the publicly reachable base URL of the backend
     * @param workspaceId the workspace the merge policy is read from
     * @param repositoryId the repository to scan
     */
    public static String generate(String backendUrl, String workspaceId, String repositoryId) {
        StringBuilder yaml = new StringBuilder();
        yaml.append("# Generated by LivingDocs — do not edit by hand.\n");
        yaml.append("#\n");
        yaml.append("# This workflow does not decide whether a pull request may be merged.\n");
        yaml.append("# It asks LivingDocs, which reads the workspace's merge policy and the\n");
        yaml.append("# open documentation drift alerts, and answers. Change the policy in the\n");
        yaml.append("# workspace settings — this file stays the same.\n");
        yaml.append("name: livingdocs-drift\n\n");
        yaml.append("on:\n");
        yaml.append("  pull_request:\n");
        yaml.append("    types: [opened, synchronize, reopened]\n\n");
        yaml.append("jobs:\n");
        yaml.append("  drift:\n");
        yaml.append("    runs-on: ubuntu-latest\n");
        yaml.append("    steps:\n");
        yaml.append("      - name: Checkout\n");
        yaml.append("        uses: actions/checkout@v4\n");
        yaml.append("        with:\n");
        yaml.append("          fetch-depth: 0\n\n");
        yaml.append("      - name: Ask LivingDocs whether this pull request may merge\n");
        yaml.append("        env:\n");
        yaml.append("          LIVINGDOCS_BACKEND_URL: ").append(backendUrl).append("\n");
        yaml.append("          LIVINGDOCS_WORKSPACE_ID: ").append(workspaceId).append("\n");
        yaml.append("          LIVINGDOCS_REPOSITORY_ID: ").append(repositoryId).append("\n");
        yaml.append("          LIVINGDOCS_CI_TOKEN: ${{ secrets.LIVINGDOCS_CI_TOKEN }}\n");
        yaml.append("        run: |\n");
        yaml.append("          set -euo pipefail\n");
        yaml.append("\n");
        yaml.append("          # The verdict endpoint also runs the drift scan for this pull\n");
        yaml.append("          # request, so the alerts it reasons about are the ones this\n");
        yaml.append("          # pull request introduces.\n");
        yaml.append("          RESPONSE=$(curl -fsSL -X GET \\\n");
        yaml.append("            -H \"X-LivingDocs-CI-Token: $LIVINGDOCS_CI_TOKEN\" \\\n");
        yaml.append("            -H \"Accept: application/json\" \\\n");
        yaml.append("            \"$LIVINGDOCS_BACKEND_URL/api/v1/cicd/workspaces/$LIVINGDOCS_WORKSPACE_ID/repositories/$LIVINGDOCS_REPOSITORY_ID/merge-gate?pullRequestNumber=${{ github.event.pull_request.number }}\")\n");
        yaml.append("\n");
        yaml.append("          echo \"$RESPONSE\" | jq .\n");
        yaml.append("\n");
        yaml.append("          BLOCKED=$(echo \"$RESPONSE\" | jq -r '.blocked // false')\n");
        yaml.append("          REASON=$(echo \"$RESPONSE\" | jq -r '.reason // \"unknown\"')\n");
        yaml.append("          POLICY=$(echo \"$RESPONSE\" | jq -r '.policy // \"UNKNOWN\"')\n");
        yaml.append("\n");
        yaml.append("          if [ \"$BLOCKED\" = \"true\" ]; then\n");
        yaml.append("            echo \"::error::Merge blocked by the LivingDocs merge policy ($POLICY): $REASON\"\n");
        yaml.append("            exit 1\n");
        yaml.append("          fi\n");
        yaml.append("\n");
        yaml.append("          echo \"Merge allowed by the LivingDocs merge policy ($POLICY).\"\n");

        return yaml.toString();
    }
}
